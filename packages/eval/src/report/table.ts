import { roundtripRate } from "../scoring/index.js";
import { classStatus, type MutationClassResult, type Tier1Report } from "./types.js";

const ROUNDTRIP_HEADERS = [
  "#",
  "mutation class",
  "kind",
  "cases",
  "roundtrip_after_mutation_rate",
  "restored/expected",
  "residual",
  "status",
] as const;

const IDENTITY_HEADERS = [
  "#",
  "mutation class",
  "probes",
  "rightful value",
  "withheld",
  "foreign value (I1)",
  "category-blind repairs",
] as const;

export function formatTier1Table(report: Tier1Report): string {
  return renderTable(ROUNDTRIP_HEADERS, report.classes.map(toRoundtripRow));
}

export function formatIdentityTable(report: Tier1Report): string {
  return renderTable(IDENTITY_HEADERS, report.classes.map(toIdentityRow));
}

export function formatPercent(rate: number): string {
  return `${(rate * 100).toFixed(1)}%`;
}

function renderTable(
  headers: readonly string[],
  rows: readonly (readonly string[])[],
): string {
  const widths = headers.map((header, column) =>
    Math.max(header.length, ...rows.map((row) => row[column].length)),
  );
  const line = (cells: readonly string[]): string =>
    `| ${cells.map((cell, i) => cell.padEnd(widths[i])).join(" | ")} |`;
  const divider = `|${widths.map((w) => "-".repeat(w + 2)).join("|")}|`;
  return [line(headers), divider, ...rows.map(line)].join("\n");
}

function toRoundtripRow(result: MutationClassResult): readonly string[] {
  const rate = roundtripRate(result);
  return [
    String(result.id),
    result.name,
    result.kind,
    String(result.cases),
    rate === null ? "n/a" : formatPercent(rate),
    `${result.restored}/${result.expected}`,
    String(result.residualTokens),
    classStatus(result),
  ];
}

function toIdentityRow(result: MutationClassResult): readonly string[] {
  return [
    String(result.id),
    result.name,
    String(result.identity.probes),
    String(result.identity.rightfulValue),
    String(result.identity.withheld),
    String(result.identity.foreignValue),
    String(result.identity.categoryBlindRepairs),
  ];
}

export function formatBaselineMarkdown(report: Tier1Report): string {
  return `${[...header(report), ...roundtripSection(report), ...identitySection(report), ...notesSection(report)].join("\n")}\n`;
}

function header(report: Tier1Report): readonly string[] {
  return [
    "# Tier-1 mutation baseline",
    "",
    "Generated by `bun run --filter '@pii-remover/eval' tier1`. Deterministic:",
    "regenerate and commit whenever the restorer, the mutation catalog or the",
    "corpus changes, and read the diff as the quality delta.",
    "",
    `- corpus entries: **${report.corpusEntries}**`,
    `- distinct tokens minted: **${report.corpusTokens}**`,
    `- mutation cases scored: **${report.totalCases}**`,
    `- token-identity probes: **${report.identity.probes}**`,
    `- \`false_restoration_rate\`: **${formatPercent(report.falseRestorationRate)}** — hard invariant, must be exactly 0 (plan §3.2, §8 I1)`,
    "",
  ];
}

function roundtripSection(report: Tier1Report): readonly string[] {
  return [
    "## Per-mutation-class roundtrip",
    "",
    formatTier1Table(report),
    "",
    "`roundtrip_after_mutation_rate` = distinct synthetic values recovered /",
    "values a correct restorer owes. Probe classes owe nothing, so they read",
    "`n/a`; their contract is the identity table below.",
    "",
    "- `ok` — surface mutation, fully recovered.",
    "- `baseline-gap` — known-lossy today. Plan Phase C (levers L3/L4) has to move these; this number is what proves it moved.",
    "- `probe-withheld` — the mutation re-pointed or invented a token and nothing came back. Correct, fail-closed.",
    "- `category-blind-repair` — the token's own value came back, but the repair accepted a category that did not match. Reported, not fatal.",
    "- `regression` / `invariant-violated` — failures; the runner exits non-zero.",
    "",
  ];
}

function identitySection(report: Tier1Report): readonly string[] {
  return [
    "## Token identity (invariant I1)",
    "",
    "One probe per minted token per class: the token is mutated in isolation,",
    "restored, and the verdict is which vault entry's value came back.",
    "",
    formatIdentityTable(report),
    "",
  ];
}

function notesSection(report: Tier1Report): readonly string[] {
  const withNotes = report.classes.filter((result) => result.notes.length > 0);
  if (withNotes.length === 0) return [];
  const lines = ["## Notes", ""];
  for (const result of withNotes) {
    lines.push(`**${result.id} — ${result.name}** (${result.description})`);
    lines.push("");
    for (const note of result.notes) lines.push(`- ${note}`);
    lines.push("");
  }
  return lines;
}
